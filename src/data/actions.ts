export function actionsFor(track: Track, grade: GradeId): ActionDef[] {
  const tech = new Set([
    'model-layouts',
    'clash-cycle',
    'learn-revit',
    'peer-check',
    'drawing-set',
    'site-visit',
    'ask-mentor',
    'work-across',
    'cpd-friday',
    'chartership-log',
    'risk-review',
    'conduct-dilemma',
    'ask-feedback',
    'internal-meeting',
    'unutilized',
    'leave',
    'overtime',
    'timesheets',
    'lunch-learn',
    'automate',
  ])
  const eng = new Set([
    'calc-package',
    'drawing-set',
    'design-review',
    'site-visit',
    'ask-mentor',
    'work-across',
    'cpd-friday',
    'chartership-log',
    'risk-review',
    'carbon-option',
    'conduct-dilemma',
    'requirements-brief',
    'ask-feedback',
    'client-meeting',
    'internal-meeting',
    'unutilized',
    'leave',
    'overtime',
    'timesheets',
    'lunch-learn',
    'automate',
  ])
  if (grade === 'engineer' || grade === 'senior' || grade === 'associate') {
    eng.add('mentor-junior')
    eng.add('client-meeting')
    eng.add('evaluate-built')
  }
  if (grade === 'seniorTechnician' || grade === 'bimLead' || grade === 'leadCoordinator') {
    tech.add('mentor-junior')
    tech.add('carbon-option')
  }
  const pool = track === 'technician' ? tech : eng
  return ACTIONS.filter((a) => pool.has(a.id))
}

